-- SLICE-FS02-01. Se aplică de administratorul MariaDB pe serverul AVACONT.
-- Nicio dependență de schema K-BOT. CF se înregistrează cu cifre, fără RO.
-- Codul fiscal (CF) este cheia unică a unității: nu există coloană DC. Pentru o bază creată cu schema veche (cu DC)
-- se rulează sql/SLICE-FS02-01_fiscolino_cf_cheie_migrare.sql, nu acest fișier.

CREATE DATABASE IF NOT EXISTS `FISCOLINO` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `FISCOLINO`;

CREATE TABLE IF NOT EXISTS `UNITATI` (
    `CF` VARCHAR(13) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    PRIMARY KEY (`CF`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `UNITATI_UTILIZATORI` (
    `UN` VARCHAR(255) NOT NULL,
    `CF` VARCHAR(13) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    PRIMARY KEY (`UN`, `CF`),
    CONSTRAINT `FK_UU_UNITATI` FOREIGN KEY (`CF`) REFERENCES `UNITATI` (`CF`) ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `UTILIZATORI_CERTIFICATE` (
    `AMPRENTA` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'SHA-256 hex cu litere mici, calculat din certificatul public DER',
    `UN` VARCHAR(255) NOT NULL,
    `ACTIV` TINYINT(1) NOT NULL DEFAULT 1,
    PRIMARY KEY (`AMPRENTA`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `PORTAL_SESIUNI` (
    `TOKEN_HASH` BINARY(32) NOT NULL,
    `UN` VARCHAR(255) NOT NULL,
    `AMPRENTA` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `EXPIRA_LA` DATETIME NOT NULL COMMENT 'UTC',
    PRIMARY KEY (`TOKEN_HASH`),
    KEY `IX_PORTAL_SESIUNI_EXPIRA_LA` (`EXPIRA_LA`),
    FOREIGN KEY (`AMPRENTA`) REFERENCES `UTILIZATORI_CERTIFICATE` (`AMPRENTA`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `EF_TOKEN_START` (
    `STATE` CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `UN` VARCHAR(255) NOT NULL,
    `CIF` VARCHAR(13) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'CF-ul unității',
    `AMPRENTA` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `EXPIRA_LA` DATETIME NOT NULL COMMENT 'UTC',
    PRIMARY KEY (`STATE`),
    KEY `IX_EF_TOKEN_START_EXPIRA_LA` (`EXPIRA_LA`),
    CONSTRAINT `FK_EFTS_UNITATI` FOREIGN KEY (`CIF`) REFERENCES `UNITATI` (`CF`) ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (`AMPRENTA`) REFERENCES `UTILIZATORI_CERTIFICATE` (`AMPRENTA`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `EF_TOKEN` (
    `CIF` VARCHAR(13) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'CF-ul unității',
    `ACCES_CRYPT` MEDIUMTEXT CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `REFRESH_CRYPT` MEDIUMTEXT CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `ACCES_EXPIRA_LA` DATETIME NOT NULL COMMENT 'UTC',
    `REFRESH_EXPIRA_LA` DATETIME NOT NULL COMMENT 'UTC',
    `AUTORIZAT_LA` DATETIME NOT NULL COMMENT 'UTC',
    `AUTORIZAT_DE` VARCHAR(255) NOT NULL,
    `CERT_ETICHETA` VARCHAR(255) NULL,
    `CERT_AMPRENTA` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `REFRESH_LA` DATETIME NULL COMMENT 'UTC',
    `ULTIMA_EROARE` VARCHAR(255) NULL,
    `ULTIMA_EROARE_LA` DATETIME NULL COMMENT 'UTC',
    PRIMARY KEY (`CIF`),
    CONSTRAINT `FK_EFT_UNITATI` FOREIGN KEY (`CIF`) REFERENCES `UNITATI` (`CF`) ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
