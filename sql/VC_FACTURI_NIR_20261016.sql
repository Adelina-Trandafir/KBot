CREATE TABLE IF NOT EXISTS VC_FACTURI (
  ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
  PARTENER_ID INT(11) NULL,
  NUMAR VARCHAR(255) NOT NULL,
  DATA DATE NULL,
  MONEDA VARCHAR(3) NOT NULL DEFAULT 'RON',
  TOTAL DECIMAL(20,4) NULL,
  TOTAL_CONFIRMAT TINYINT NOT NULL DEFAULT 0,
  STARE VARCHAR(24) NOT NULL DEFAULT 'IN_LUCRU',
  MIGRATA TINYINT NOT NULL DEFAULT 0,
  LOCALA TINYINT NOT NULL DEFAULT 0,
  REUNITA_IN INT UNSIGNED NULL,
  VERSION BIGINT NOT NULL DEFAULT 1,
  CREAT_DE VARCHAR(255) NOT NULL,
  CREAT_LA DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (ID),
  KEY IX_VC_FACTURI_CANDIDAT (PARTENER_ID,DATA),
  CONSTRAINT FK_VC_FACTURI_REUNITA FOREIGN KEY (REUNITA_IN) REFERENCES VC_FACTURI(ID) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb3 COLLATE=utf8mb3_general_ci;

