-- Acest script este independent de VC07-20, VC07-21 și VC06-44.
CREATE TABLE IF NOT EXISTS VC_TransferUnitati (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    SURSA_SUBUNITATE BIGINT NOT NULL,
    SURSA_GESTIUNE BIGINT NOT NULL,
    SURSA_EXERCITIU BIGINT NOT NULL,
    IDBT BIGINT NOT NULL,
    PREDATOR BIGINT NULL,
    DEST_SUBUNITATE BIGINT NOT NULL,
    DEST_GESTIUNE BIGINT NOT NULL,
    DEST_EXERCITIU BIGINT NOT NULL,
    PRIMITOR BIGINT NULL,
    DEST_NIR BIGINT NULL,
    DEST_BP BIGINT NULL,
    DATA_BU DATE NOT NULL,
    EXPLICATIE VARCHAR(255) NULL,
    ANULAT TINYINT NOT NULL DEFAULT 0,
    MOTIV_ANULARE VARCHAR(255) NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY UQ_TRANSFER_UNITATI_BT (SURSA_SUBUNITATE, SURSA_GESTIUNE, SURSA_EXERCITIU, IDBT),
    KEY IX_TRANSFER_UNITATI_NIR (DEST_SUBUNITATE, DEST_GESTIUNE, DEST_EXERCITIU, DEST_NIR),
    KEY IX_TRANSFER_UNITATI_BP (DEST_SUBUNITATE, DEST_GESTIUNE, DEST_EXERCITIU, DEST_BP)
) ENGINE=InnoDB;

-- Compatibil și cu bazele care au deja prima versiune a tabelei BU.
ALTER TABLE VC_TransferUnitati MODIFY COLUMN PRIMITOR BIGINT NULL;

CREATE TABLE IF NOT EXISTS VC_TransferUnitati_Linii (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    BU_ID BIGINT NOT NULL,
    SURSA_VARIANTA BIGINT NOT NULL,
    SURSA_BC BIGINT NULL,
    DEST_VARIANTA BIGINT NOT NULL,
    ORIGINE_SUBUNITATE BIGINT NULL,
    ORIGINE_GESTIUNE BIGINT NULL,
    ORIGINE_VARIANTA BIGINT NULL,
    PRIMARY KEY (ID),
    KEY IX_TRANSFER_UNITATI_LINII_BU (BU_ID),
    CONSTRAINT FK_TRANSFER_UNITATI_LINII_BU FOREIGN KEY (BU_ID) REFERENCES VC_TransferUnitati (ID)
) ENGINE=InnoDB;
