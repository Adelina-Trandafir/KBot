-- Cancelling the ADE document retains this reservation and its audit trail.
CREATE TABLE IF NOT EXISTS `AD_EXTRASE_ASOCIERI` (
  `IDFXE` INT NOT NULL,
  `SUBUNIT_ID` INT NOT NULL,
  `IDP` INT NOT NULL,
  `IDS_ANTERIOR` INT NOT NULL,
  `IDS` INT NOT NULL,
  `IDZ` INT NOT NULL,
  `IDL` INT NOT NULL,
  `IDPL` INT NOT NULL,
  `IDA` INT NOT NULL,
  `SURSA_HASH` CHAR(64) NOT NULL,
  `ASOCIAT_DE` VARCHAR(255) NOT NULL,
  `ASOCIAT_LA` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`IDFXE`),
  UNIQUE KEY `UQ_AD_EXTRASE_IDPL` (`IDPL`),
  UNIQUE KEY `UQ_AD_EXTRASE_IDA` (`IDA`),
  KEY `IX_AD_EXTRASE_SUBUNIT_COPIL` (`SUBUNIT_ID`, `IDP`),
  CONSTRAINT `FK_AD_EXTRASE_SURSA` FOREIGN KEY (`IDFXE`) REFERENCES `FX_Extrase` (`IDFXE`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `FK_AD_EXTRASE_SUBUNIT` FOREIGN KEY (`SUBUNIT_ID`) REFERENCES `AD_Subunits` (`SubunitId`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `FK_AD_EXTRASE_COPIL` FOREIGN KEY (`IDP`) REFERENCES `AD_Platitori` (`IDP`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `FK_AD_EXTRASE_PLATITOR_VECHI` FOREIGN KEY (`IDS_ANTERIOR`) REFERENCES `AD_Platitori_sub` (`IDS`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `FK_AD_EXTRASE_PLATITOR` FOREIGN KEY (`IDS`) REFERENCES `AD_Platitori_sub` (`IDS`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `FK_AD_EXTRASE_PREZENTA` FOREIGN KEY (`IDZ`) REFERENCES `AD_Prezenta` (`IDZ`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `FK_AD_EXTRASE_LUNA` FOREIGN KEY (`IDL`) REFERENCES `AD_LunaD` (`IDL`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `FK_AD_EXTRASE_PLATA` FOREIGN KEY (`IDPL`) REFERENCES `AD_Plati` (`IDPL`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `FK_AD_EXTRASE_DOCUMENT` FOREIGN KEY (`IDA`) REFERENCES `AD_AlteDoc` (`IDA`) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb3 COLLATE=utf8mb3_general_ci;
