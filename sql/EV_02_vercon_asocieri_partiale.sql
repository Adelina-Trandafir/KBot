-- Executare MANUALĂ pe AVACONT_SURSA, apoi sincronizarea structurii în DC-uri.
-- Nu se execută pe AVACONT_COMUN. Necesită EV_01_primite_vercon.sql.
-- Legăturile vechi, integrale, rămân în EF_PrimiteVerconNir.
CREATE TABLE IF NOT EXISTS EF_VERCON_ASOCIERI (
  ID_TRIMITERE INT(11) NOT NULL,
  PRIMARY KEY (ID_TRIMITERE),
  CONSTRAINT FK_EV_ASOC_TRIMITERE FOREIGN KEY (ID_TRIMITERE)
    REFERENCES EF_PrimiteVercon (IdTrimitere) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb3 COLLATE=utf8mb3_general_ci;

CREATE TABLE IF NOT EXISTS EF_VERCON_ALOCARI (
  ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  ID_TRIMITERE INT(11) NOT NULL,
  ID_LINIE INT(11) NOT NULL,
  SUBUNIT_ID INT UNSIGNED NOT NULL,
  GESTIUNE_ID INT UNSIGNED NOT NULL,
  EXERCITIU_ID INT UNSIGNED NOT NULL,
  NIR_ID INT UNSIGNED NOT NULL,
  NIR_VERSION INT UNSIGNED NOT NULL,
  INTRARE_ID INT UNSIGNED NOT NULL,
  PRODUS_PRET_ID INT UNSIGNED NOT NULL,
  CANT_FACTURA DECIMAL(20,4) NOT NULL,
  CANT_NIR DECIMAL(20,4) NOT NULL,
  CANT_SURSA DECIMAL(20,4) NOT NULL,
  PRET_SURSA DECIMAL(20,4) NOT NULL,
  CREAT_DE VARCHAR(255) NOT NULL,
  CREAT_LA DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (ID),
  UNIQUE KEY UQ_EV_ALOC (ID_TRIMITERE,ID_LINIE,SUBUNIT_ID,GESTIUNE_ID,EXERCITIU_ID,INTRARE_ID),
  KEY IX_EV_ALOC_NIR (SUBUNIT_ID,GESTIUNE_ID,EXERCITIU_ID,NIR_ID),
  CONSTRAINT FK_EV_ALOC_ASOC FOREIGN KEY (ID_TRIMITERE)
    REFERENCES EF_VERCON_ASOCIERI (ID_TRIMITERE) ON DELETE CASCADE,
  CONSTRAINT FK_EV_ALOC_LINIE FOREIGN KEY (ID_LINIE)
    REFERENCES EF_PrimiteLinii (IdLinie) ON DELETE CASCADE
  -- Fără FK spre VC_*: migrarea poate reîncărca aceste tabele.
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb3 COLLATE=utf8mb3_general_ci;

CREATE TABLE IF NOT EXISTS EF_VERCON_CORELARI (
  CUI VARCHAR(64) NOT NULL,
  NUME_HASH CHAR(64) NOT NULL,
  NUME_EFACTURA TEXT NOT NULL,
  SUBUNIT_ID INT UNSIGNED NOT NULL,
  GESTIUNE_ID INT UNSIGNED NOT NULL,
  PRODUS_ID INT UNSIGNED NOT NULL,
  NUME_VERCON VARCHAR(255) NOT NULL,
  CONFIRMAT_DE VARCHAR(255) NOT NULL,
  CONFIRMAT_LA DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (CUI,NUME_HASH,SUBUNIT_ID,GESTIUNE_ID,PRODUS_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb3 COLLATE=utf8mb3_general_ci;
