// ME02-01: reads MariaDB_Schema/AVACONT_SURSA.sql (the template every unit database follows) and writes
// sql/ME02_01_date_creare_modificare.sql: the missing "created" / "last changed" columns, tables that already
// have them are left alone. Run:  node tools/Me02Dates/gen_dates_ddl.js   (from the repository root)
// Nothing is executed anywhere; the operator runs the .sql on AVACONT_SURSA and schema_sync carries it to the units.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..', '..');
const sql = fs.readFileSync(path.join(root, 'MariaDB_Schema', 'AVACONT_SURSA.sql'), 'utf8');

// Tables that never get the columns, with the reason (shown in the generated file and in the worklog).
const SKIP = {
  '_snap_clsf': 'snapshot copy without a primary key',
  'AD_Lock': 'lock table, rows live seconds',
  'FX_NumberLock': 'lock table, rows live seconds',
  'VC_ContextLock': 'lock table, rows live seconds',
  'AD_PortalChallenges': 'one-time challenges, rows live minutes',
  'VC_Audit': 'append-only audit, rows are never changed',
  'Interogari_Unice': 'append-only ledger, rows are never changed',
};
// Names that already mean "this row was created". Event times such as ClosedAt / ConfirmedAt / ImportedAt do NOT count:
// they say when something happened to the row later, so those tables still get a real created column.
const CREATED_NAMES = new Set(['createdat', 'dataadaugare', 'dataadugare', 'datacreare', 'dti', 'creatla', 'at', 'rulatla']);
// Family prefixes that use CreatedAt / UpdatedAt; every other table uses DataAdaugare / DataModificare.
const ENGLISH_FAMILY = /^(VC_|AD_)/;

const re = /CREATE TABLE `([^`]+)`\s*\(([\s\S]*?)\n\)\s*ENGINE/g;
let m; const tables = [];
while ((m = re.exec(sql))) {
  const name = m[1]; const cols = []; let hasPk = false;
  for (const raw of m[2].split('\n')) {
    const l = raw.trim();
    const c = /^`([^`]+)`\s+(\w+)(.*)$/.exec(l);
    if (c) cols.push({ n: c[1], t: c[2].toLowerCase(), r: c[3] });
    if (/^PRIMARY KEY/.test(l)) hasPk = true;
  }
  tables.push({ name, cols, hasPk });
}

const isTime = (c) => c.t === 'datetime' || c.t === 'timestamp';
const out = []; const report = { alreadyBoth: [], skipped: [], added: [], clashes: [] };

for (const t of tables) {
  if (SKIP[t.name]) { report.skipped.push([t.name, SKIP[t.name]]); continue; }
  if (!t.hasPk) { report.skipped.push([t.name, 'no primary key']); continue; }
  const hasModified = t.cols.some((c) => isTime(c) && (/on update current_timestamp/i.test(c.r) || c.n.toLowerCase() === 'datamodif'));
  const hasCreated = t.cols.some((c) => isTime(c) &&
    (CREATED_NAMES.has(c.n.toLowerCase()) || (/default current_timestamp\(\)/i.test(c.r) && !/on update/i.test(c.r))));
  if (hasModified && hasCreated) { report.alreadyBoth.push(t.name); continue; }
  const english = ENGLISH_FAMILY.test(t.name);
  const createdName = english ? 'CreatedAt' : 'DataAdaugare';
  const modifiedName = english ? 'UpdatedAt' : 'DataModificare';
  const names = new Set(t.cols.map((c) => c.n.toLowerCase()));
  const needCreated = !hasCreated; const needModified = !hasModified;
  if ((needCreated && names.has(createdName.toLowerCase())) || (needModified && names.has(modifiedName.toLowerCase()))) {
    report.clashes.push(t.name); continue;   // a column of that name exists but is not a datetime of the kind we expect
  }
  const adds = [];
  if (needCreated) adds.push("ADD COLUMN IF NOT EXISTS `" + createdName + "` datetime NULL DEFAULT NULL COMMENT 'ME02-01: when the row was created (NULL = it existed before ME02-01)'");
  if (needModified) adds.push("ADD COLUMN IF NOT EXISTS `" + modifiedName + "` datetime NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP COMMENT 'ME02-01: when the row was last changed (NULL = not changed since ME02-01)'");
  let block = '-- ' + t.name + (needCreated ? ' [+' + createdName + ']' : '') + (needModified ? ' [+' + modifiedName + ']' : '') + '\n';
  block += 'ALTER TABLE `' + t.name + '`\n  ' + adds.join(',\n  ') + ';\n';
  // The default of the created column is set AFTER the column exists, so the rows that are already there stay NULL
  // instead of all receiving the time of this script (a lie about when they were created). Metadata-only change.
  if (needCreated) block += 'ALTER TABLE `' + t.name + '` ALTER COLUMN `' + createdName + '` SET DEFAULT current_timestamp();\n';
  out.push(block);
  report.added.push([t.name, needCreated ? createdName : '', needModified ? modifiedName : '']);
}

const header = [
  '-- ME02-01: "created" and "last changed" dates for the tables that lack them.',
  '-- Generated by tools/Me02Dates/gen_dates_ddl.js from MariaDB_Schema/AVACONT_SURSA.sql. Safe to run twice.',
  '-- Run it on AVACONT_SURSA (USE `AVACONT_SURSA`;), then let schema_sync carry it to the unit databases.',
  '-- Existing rows keep NULL in the new columns: NULL means "before ME02-01", it is not a date.',
  '-- The "last changed" column is filled by MariaDB itself on every UPDATE that changes a value; no application code is involved.',
  '-- Tables left alone: ' + report.alreadyBoth.length + ' already have both; ' + report.skipped.length + ' skipped on purpose:',
  ...report.skipped.map(([n, why]) => '--     ' + n + ' (' + why + ')'),
  '', ''].join('\n');
fs.writeFileSync(path.join(root, 'sql', 'ME02_01_date_creare_modificare.sql'), header + out.join('\n'));

console.log('tables', tables.length, '| already both', report.alreadyBoth.length, '| skipped', report.skipped.length,
  '| altered', report.added.length, '| clashes', report.clashes.length);
console.log('created+modified added:', report.added.filter((a) => a[1] && a[2]).length,
  '| only modified added:', report.added.filter((a) => !a[1] && a[2]).length,
  '| only created added:', report.added.filter((a) => a[1] && !a[2]).length);
console.log('CLASHES:', report.clashes.join(' ') || '-');
fs.writeFileSync(path.join(root, 'tools', 'Me02Dates', 'report.json'), JSON.stringify(report, null, 1));
