// Access import semantics only. The physical MariaDB schema comes from AVACONT_SURSA
// and is read at runtime through KBot.Migrator.TargetSchema. This tool emits no SQL.
const fs = require('fs'), path = require('path');
const { TZ, parseTz, cls } = require('./lib_tz');

const GEST = ['Masini', 'Produse', 'ProduseP', 'ProduseM', 'Clienti', 'ComisieNIR', 'ComisieInventar', 'TVA', 'FeluriMancare', 'Retetar', 'OI_Produse'];
const EXER = ['NIR', 'Intrari', 'IntrariStorno', 'Iesiri_H', 'Iesiri', 'IesiriRetur', 'OI_Predare', 'OI_Transfer', 'OI_Casare', 'LABC', 'ListaAlimente', 'LegBCLA', 'MicDejun', 'Dejun', 'Cina'];
const ALL = [...GEST, ...EXER];
const EXTRA = { ProduseM: [{ n: 'ValoareLunara', type: 'Double', size: 8, req: false, def: '' }] };
const SKIP_FIELDS = { NIR: new Set(['IDF', 'IDFV']) };
const scope = (t) => EXER.includes(t) ? 'E' : 'G';
const vname = (t) => `VC_${t}`;
const rel = fs.readFileSync(path.join(TZ, 'relationships.md'), 'utf8').replace(/\r/g, '').split('\n')
  .filter((line) => line.startsWith('- **')).map((line) => {
    const m = line.match(/: (\S+?)\.(\S+) -> (\S+?)\.(\S+?)(?: \[(.*)\])?(?: \((.*)\))?$/);
    return m ? { p: m[1], pf: m[2], c: m[3], cf: m[4] } : null;
  }).filter(Boolean).filter((r) => ALL.includes(r.p) && ALL.includes(r.c));

// Source-row identity policy. An Access key which is itself a reference is kept
// as a reference; the target identity is discovered from the live AUTO_INCREMENT.
const info = {};
for (const t of ALL) {
  const parsed = parseTz(t);
  const pkIndex = parsed.idx.find((index) => /PRIMARY/.test(index.flags));
  let sourceKey = pkIndex && !pkIndex.cols.includes(',') ? pkIndex.cols.trim() : null;
  if (sourceKey && rel.some((r) => r.c === t && r.cf === sourceKey)) sourceKey = null;
  info[t] = { fields: [...parsed.fields, ...(EXTRA[t] || [])], sourceKey };
}
const LOGICAL = {
  'IntrariStorno.IdIntrare': 'NIR', 'IntrariStorno.IdProdus': 'ProduseP', 'ProduseM.IdProdus': 'ProduseP', 'OI_Transfer.IDC_OLD': 'Clienti',
  'NIR.IdMasina': 'Masini', 'Iesiri_H.IdMasina': 'Masini', 'OI_Casare.IdMasina': 'Masini', 'OI_Predare.IdMasina': 'Masini', 'OI_Transfer.IdMasina': 'Masini',
  'OI_Predare.IdBonConsum': 'Iesiri_H', 'NIR.IdStorno': 'NIR',
};
const GROUPS = new Set(['OI_Predare.IDBP', 'OI_Transfer.IDBT', 'OI_Casare.IDBC', 'OI_Produse.IDBP', 'OI_Produse.IDBT']);

// Stable source dependency order is only a tie-breaker for the live-FK sorter.
const order = [], active = new Set();
function visit(t) {
  if (order.includes(t)) return;
  if (active.has(t)) throw new Error(`Cyclic Access dependency: ${t}`);
  active.add(t);
  for (const r of rel.filter((item) => item.c === t && item.p !== t)) visit(r.p);
  active.delete(t);
  order.push(t);
}
for (const t of ALL) visit(t);

const mapping = { generated: 'VERCON/tools/import_map.js', tables: [] };
for (const t of order) {
  const columns = [];
  for (const field of info[t].fields) {
    if (field.n === info[t].sourceKey) continue;
    const fieldClass = cls(t, field)[0];
    const fk = rel.find((r) => r.c === t && r.cf === field.n && r.p !== 'Furnizori');
    let link = null;
    if (fieldClass === 'CHEIE') {
      const key = `${t}.${field.n}`;
      if (['MicDejun', 'Dejun', 'Cina'].includes(t) && field.n === 'IdFel') link = { kind: 'meal_type' };
      else if (t === 'NIR' && field.n === 'IDF') link = { kind: 'supplier' };
      else if (SKIP_FIELDS[t]?.has(field.n)) link = { kind: 'skip' };
      else if (key === 'OI_Produse.IDBC') link = { kind: 'oi_document' };
      else if (key === 'OI_Produse.IDBO') link = { kind: 'origin' };
      else if (GROUPS.has(key)) link = { kind: 'group', group: field.n };
      else if (field.type === 'AutoNumber') link = { kind: 'tech' };
      else if (fk) link = { kind: 'fk', parent: fk.p, parentField: fk.pf };
      else if (LOGICAL[key]) link = { kind: 'logical', parent: LOGICAL[key], parentField: info[LOGICAL[key]].sourceKey };
      else link = { kind: 'open' };
    }
    columns.push({ name: field.n, cls: fieldClass, link });
  }
  mapping.tables.push({ name: t, vname: vname(t), scope: scope(t), source_key: info[t].sourceKey, columns });
}
fs.writeFileSync(path.join(__dirname, '..', 'VRC.Migrator', 'import_map.json'), JSON.stringify(mapping, null, 1) + '\n');

// Application scope is a routing rule, not a physical schema declaration.
const py = '"""GENERATED by VERCON/tools/import_map.js. Application scope of imported VC_ tables."""\n'
  + `GESTIUNE_TABLES = frozenset(${JSON.stringify(GEST.map(vname))})\n`
  + `EXERCITIU_TABLES = frozenset(${JSON.stringify(EXER.map(vname))})\n`;
fs.writeFileSync(path.join(__dirname, '..', '..', 'PYTHON', 'routes', 'vercon', 'tables.py'), py.replace(/\[/g, '{').replace(/\]/g, '}'));

// A diagram of source remapping rules, not a snapshot of the live MariaDB FKs.
const diagram = ['%% Access import mapping; physical schema: AVACONT_SURSA on the server.', 'erDiagram',
  ...rel.map((r) => `  ${vname(r.p)} ||--o{ ${vname(r.c)} : "${r.cf}"`)];
fs.writeFileSync(path.join(__dirname, '..', 'SCHEMA_VC_RELATII.mmd'), diagram.join('\n') + '\n');
